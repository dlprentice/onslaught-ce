// PCText.cpp: the PC port's hard-coded strings (not in Stuart's release; rebuilt from the retail object after
// OggFileRead.obj, 00524830..00527810). The PC's option screens, setup and error texts are not in text.stf: one
// switch per front-end language returns each id's text, and an id a language leaves out (23 in each) or any id
// in another language falls through to the English switch. The object's name is not known.
//
// VC6 keeps one copy of a return that several switches share. Its cross-jumping (C2 0x1073d211) walks the exit label's
// reference list from the head: the first jump keeps its copy, and each later jump with the same tail moves into it (a
// run of identical cases moves as one region). The returns first jump to the function's return label, which C2's
// label pass (0x10704de1) merges into the exit label one reference at a time, so the list runs in source order:
// language 0's returns, English's, then languages 1..4. Only language 0 falling through into the English switch (with
// languages 1..4 and other languages jumping back to it) keeps the shared English texts in language 0's block, as
// retail does. A forward goto (tried from language 0's switch) reverses the list and moves every owner; all the gotos
// here go backwards. Language 4's "PAUSA" (0x7c) and "TILDE" (0x85) are in id order, so languages 3 and 1 keep them.
// STAND-IN (cross-jump order): retail keeps four texts language 0 shares with English (0x19,
// 0x21, 0x41, 0xef) in the English block. Their English copies are returns inside language 0's switch, just before
// language 0's own case, reached by goto from the English switch. Their jumps are made between language 0's previous
// case and its own, so each anchors and language 0's own copy moves into it, and layout places them in the English
// block (0x19 and 0x21 after 0x07, 0x41 after the empty string, 0xef before "<no text>"). A patched C2 that moves
// English's four jumps to just those list positions matched first; moved to the head instead, each takes the run of
// identical cases before it into the English block. Dropping language 0's four cases puts the four blocks right but
// points language 0's table at the English dispatch, and both that and one return shared through a goto move "Media"
// (0x23) to language 4.

