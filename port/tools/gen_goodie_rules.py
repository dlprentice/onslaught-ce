"""Writes port/game/ce_goodie_rules.h: how each Goodie is earned, in the words the Goodies pages of Onslaught CE show.

The rules are the Onslaught Toolkit's (its Companion's Careers/GoodieUnlockRequirementService.cs, facts read from the developers' source,
and Careers/GoodieFacts.cs, how far the evidence for each goes), both public and GPL-3.0 like this repository. This script reads those two
files, puts each rule in the game's own wording (levels as the level select writes them, "2.11", Goodies by their kind and number as the
Goodies wall counts them) and writes a table of 233 rows, one for each slot of the game's table, with the SHA-256 of both inputs in the
header so that the table says what it was made from. Nothing of the original game is read.

    python3 port/tools/gen_goodie_rules.py [--source DIR] [--check]

--source names the folder holding the two files (default: the Toolkit checkout beside this repository, found as ce_career_view_tests.py
finds it). --check writes nothing and exits 1 when the committed table differs from what the inputs give.
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "port/game/ce_goodie_rules.h"
FILES = ("GoodieUnlockRequirementService.cs", "GoodieFacts.cs")
SLOTS = 233                      # the game's own table: slots 0 to 232
# the wall's kinds: the first slot of each (the same table the Service Record's Goodies page uses)
KINDS = ((0, "Biography"), (8, "Unit"), (66, "Race Level"), (74, "Extra"), (78, "Concept Art"), (201, "Cutscene"))
EVIDENCE = ("Seen in play.", "Matches the game's code.", "From the developers' source.", "Never shown.", "Reserved.")


def find_source():
    for base in (ROOT, *ROOT.parents):
        candidate = base.parent / "Onslaught-Career-Editor/companion/OnslaughtToolkit.Godot/Careers"
        if (candidate / FILES[0]).is_file():
            return candidate
    return None


def kind_name(slot):
    kind = max(k for k in KINDS if k[0] <= slot)
    return f"{kind[1]} {slot - kind[0] + 1}"


def levels(text):
    """'level 211 or 212' -> 'level 2.11 or 2.12'; 'levels' are the campaign's three-digit numbers."""
    def one(m):
        n = int(m.group(0))
        return f"{n // 100}.{n % 100:02d}"
    def run(m):
        return m.group(1) + re.sub(r"\d{3}", one, m.group(2))
    return re.sub(r"(level )(\d{3}(?: or \d{3})?)", run, text)


def words(text):
    text = levels(text)
    text = re.sub(r"Goodie (\d{3})", lambda m: kind_name(int(m.group(1))), text)
    text = re.sub(r"mission script in Race (\d)", r"a mission script in Race Level \1", text)
    text = text.replace("Unlocked by mission script", "Unlocked by a mission script")
    text = text.replace("Watch cutscene", "Watch Cutscene")
    return text


def explicit_rules(source):
    return {int(m.group(1)): m.group(2) for m in re.finditer(r'\[(\d+)\] = "([^"]*)"', source)}


def build(directory):
    directory = Path(directory)
    service = (directory / FILES[0]).read_text()
    rules = explicit_rules(service)
    order = [int(n) for n in re.search(r"CampaignWorldOrder =\s*\[(.*?)\];", service, re.S).group(1).replace("\n", " ").split(",") if n.strip()]
    if len(order) != 43 or len(rules) != 78:
        raise SystemExit(f"the inputs are not the shape this script reads: {len(order)} missions, {len(rules)} explicit rules")
    for slot, start, grade in ((range(78, 121), 78, "C"), (range(121, 164), 121, "B"), (range(164, 201), 164, "A")):
        for s in slot:
            rules[s] = f"Earn {grade} or better on level {order[s - start]}."
    for s in range(201, 233):
        rules[s] = f"Watch cutscene {33 if s == 232 else s - 200} during normal play."
    facts = (directory / FILES[1]).read_text()
    first = re.search(r"2 => GoodieEvidence\.SeenInGame,\s*0 or 8 or \(>= 74 and <= 78\) or 121 or 164 => GoodieEvidence\.GameCodeChecked", facts)
    if not first:
        raise SystemExit("GoodieFacts.cs no longer states its evidence the way this script reads it")
    def evidence(s):
        if 71 <= s <= 73:
            return 3
        if s == 2:
            return 0
        if s in (0, 8) or 74 <= s <= 78 or s in (121, 164):
            return 1
        return 2
    sha = ", ".join(f"{name} {hashlib.sha256((directory / name).read_bytes()).hexdigest()}" for name in FILES)
    lines = ["// SPDX-License-Identifier: GPL-3.0-only",
             "// port/game/ce_goodie_rules.h: how each Goodie is earned, generated by port/tools/gen_goodie_rules.py: do not edit.",
             "// Made from the Onslaught Toolkit's Companion tables (facts read from the developers' source), sha-256: " + sha + ".",
             "// One row for each of the game's 233 Goodie slots: the rule in the Goodies pages' words and how far the evidence goes",
             "// (0 seen in play, 1 matches the game's code, 2 from the developers' source, 3 never shown, 4 reserved).",
             "#ifndef CE_GOODIE_RULES_H", "#define CE_GOODIE_RULES_H", "",
             "struct SCeGoodieRule\n{\n\tconst char\t*mRule;\n\tint\t\t\tmEvidence;\n};", "",
             "static const SCeGoodieRule\tkCeGoodieRules[233] = {"]
    for s in range(SLOTS):
        lines.append(f'\t{{"{words(rules[s])}", {evidence(s)}}},\t// {s}')
    lines += ["};", "", "static const char\t*const kCeGoodieEvidence[5] = {" + ", ".join(f'"{e}"' for e in EVIDENCE) + "};", "", "#endif", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    source = Path(args.source) if args.source else find_source()
    if not source:
        print("the Toolkit's Careers folder was not found: pass --source", file=sys.stderr)
        return 2
    text = build(source)
    if args.check:
        same = OUT.is_file() and OUT.read_text() == text
        print("the table is what its inputs give" if same else "the table differs from what its inputs give")
        return 0 if same else 1
    OUT.write_text(text)
    print("wrote", OUT, f"({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
