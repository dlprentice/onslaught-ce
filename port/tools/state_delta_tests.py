"""Bounded actual delta-codec controls, optional preserved authored serializer fixtures. No game/network/device run.

The loss/reordering test models application commit explicitly; it does not execute World Apply or certify real ACKs.
Optional fixture inputs are read only and never regenerated by this runner. Monocypher and toolchains must exist.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import resource
import shutil
import struct
import subprocess
import tempfile

import deps

ROOT = Path(__file__).resolve().parents[2]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def var(n):
    result = bytearray()
    while True:
        b = n & 127
        n >>= 7
        result.append(b | (128 if n else 0))
        if not n:
            return result


def digest(data, sequence):
    return hashlib.blake2b(b"CE-state-image-v1\0" + bytes(range(32)) + struct.pack(">III", 7, sequence, len(data)) + data,
                           digest_size=32).digest()


def reference(base, target):
    """Independent canonical encoder; compares exact serialized bytes, never Python float equality."""
    wire = bytearray(b"CED1\x01\x01\0\0" + bytes(range(32)) + struct.pack(">IIIII", 7, 1, 2, len(base), len(target)) +
                     digest(base, 1) + digest(target, 2))
    i = previous = 0
    while i < len(target):
        if target[i] == (base[i] if i < len(base) else 0):
            i += 1
            continue
        begin = i
        while i < len(target) and target[i] != (base[i] if i < len(base) else 0):
            i += 1
        wire += var(begin - previous) + var(i - begin) + target[begin:i]
        previous = i
    return bytes(wire)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixtures", type=Path, help="preserved authored profile directory; read-only")
    parser.add_argument("--carrier-fixtures", type=Path, help="preserved carrier00.bin..carrier15.bin directory; read-only")
    parser.add_argument("--syntax-targets", action="store_true")
    parser.add_argument("--no-mutants", action="store_true")
    parser.add_argument("--aliases-only", action="store_true", help="focused metadata/range controls only")
    parser.add_argument("--aliases-before-ref", help="optional frozen Git source negative for the original metadata-alias witness")
    args = parser.parse_args()
    if args.aliases_only and (args.syntax_targets or args.aliases_before_ref or args.fixtures or args.carrier_fixtures):
        parser.error("--aliases-only cannot select target, before-ref or serializer-fixture gates")
    resource.setrlimit(resource.RLIMIT_CORE, (0, 0))
    parent = ROOT / "local-data/port/state-delta-tests"
    parent.mkdir(parents=True, exist_ok=True)
    out = Path(tempfile.mkdtemp(prefix="run-", dir=parent))
    stage = out / "production"
    stage.mkdir()
    pins = {}
    for relative in ("network/state_delta.h", "network/state_delta.cpp", "network/network.h", "tools/tests/state_delta_driver.cpp"):
        path = ROOT / "port" / relative
        shutil.copyfile(path, stage / path.name)
        pins["port/" + relative] = sha(path)
    pins["runner"] = sha(Path(__file__))
    mc = deps.SRC / "monocypher-4.0.2/src"
    for name in ("monocypher.c", "monocypher.h"):
        path = mc / name
        if not path.is_file():
            raise RuntimeError("already-pinned Monocypher is required; no fetch/install is performed")
        pins[str(path)] = sha(path)
        shutil.copyfile(path, stage / name)
    cc = deps.DATA / "llvm/bin/clang"
    cxx = deps.DATA / "llvm/bin/clang++"
    if not cc.is_file() or not cxx.is_file():
        raise RuntimeError("already-pinned LLVM is required")
    pins["compiler"] = sha(cxx)
    env = dict(os.environ, TMPDIR=str(out), ASAN_OPTIONS="detect_leaks=1:abort_on_error=1:disable_coredump=1")
    for key in tuple(env):
        if key.startswith("BEA_"):
            env.pop(key)
    result = {"scope": __doc__, "source_sha256": pins, "commands": [], "stages": [], "mutations": [],
              "fixture_pairs": [], "goldens": [], "limits": [
                  "Authored byte images and optional actual serializer OUTPUT fixtures, not measured gameplay traffic.",
                  "Stateless basis codec; Session must certify application ACK, retention/promotion and World validation/commit.",
                  "No ENet delivery, real World Apply, game/VM/GPU/native Windows execution or rate guarantee."]}
    receipt = out / "result.json"

    def save():
        receipt.write_text(json.dumps(result, indent=2) + "\n")

    def inputs_unchanged():
        result["source_after"] = {name: sha(ROOT / name if name.startswith("port/") else Path(__file__) if name == "runner"
                                             else cxx if name == "compiler" else Path(name)) for name in pins}
        return result["source_after"] == pins

    def run(label, command, expect=0):
        result["commands"].append([str(x) for x in command])
        proc = subprocess.run(command, env=env, capture_output=True, text=True, timeout=45)
        (out / (label + ".stdout")).write_text(proc.stdout)
        (out / (label + ".stderr")).write_text(proc.stderr)
        passed = proc.returncode == expect
        result["stages"].append({"name": label, "exit": proc.returncode, "passed": passed})
        save()
        if not passed:
            raise RuntimeError(label + " refused; see " + str(out))
        return proc

    flags = ["-O1", "-g", "-fsanitize=address,undefined", "-fno-sanitize-recover=all", "-fno-omit-frame-pointer"]
    run("crypto-build", [str(cc), "-std=c99", *flags, "-I" + str(stage), "-c", str(stage / "monocypher.c"), "-o", str(out / "crypto.o")])

    def build(label, source):
        binary = out / (label + "-driver")
        run(label + "-build", [str(cxx), "-std=c++17", "-Wall", "-Wextra", "-Werror", *flags, "-I" + str(stage),
                              str(source), str(stage / "state_delta_driver.cpp"), str(out / "crypto.o"), "-o", str(binary)])
        return binary

    binary = build("production", stage / "state_delta.cpp")
    proc = run("aliases", [str(binary), "aliases"])
    result["aliases"] = json.loads(proc.stdout)
    if args.aliases_only:
        result["passed"] = inputs_unchanged()
        save()
        print(json.dumps({"receipt": str(receipt), "passed": result["passed"], "aliases": result["aliases"]}, indent=2))
        return 0 if result["passed"] else 1
    if args.aliases_before_ref:
        proc = subprocess.run(["git", "show", args.aliases_before_ref + ":port/network/state_delta.cpp"], cwd=ROOT,
                              capture_output=True, text=True, check=True, timeout=10)
        old_source = out / "alias-before.cpp"
        old_source.write_text(proc.stdout)
        before = build("alias-before", old_source)
        proc = run("alias-before-witness", [str(before), "aliases"], expect=2)
        reason = "FAIL: size cannot alias identity.epoch"
        if proc.stderr.strip() != reason:
            raise RuntimeError("frozen alias negative must fail on the actual original witness")
        result["alias_before"] = {"ref": args.aliases_before_ref, "source_sha256": sha(old_source), "exit": 2,
                                  "reason": reason, "discriminates": True}
    for mode in ("core", "loss"):
        proc = run(mode, [str(binary), mode])
        result[mode] = json.loads(proc.stdout)

    # Cross-check independent BLAKE2b image domains, complete header and every canonical payload byte.
    golden_images = [(b"", b""), (b"\0" * 512, b"\0" * 128 + b"\x80\0\0\0\x7f\xc0\0\x19" + b"\0" * 376),
                     (bytes(range(256)), bytes(range(255, -1, -1))), (b"abc", b"abc\0\0\0"), (b"abc\xff", b"ab")]
    for index, (base, target) in enumerate(golden_images):
        a, b, wire_path = (out / (f"golden-{index}" + ext) for ext in (".base", ".target", ".wire"))
        a.write_bytes(base); b.write_bytes(target)
        run(f"golden-{index}", [str(binary), "encode", str(a), str(b), str(wire_path)])
        expected = reference(base, target)
        observed = wire_path.read_bytes()
        row = {"case": index, "wire_sha256": sha(wire_path), "size": len(observed), "passed": observed == expected}
        result["goldens"].append(row)
        if not row["passed"]:
            save(); raise RuntimeError("independent canonical/hash golden mismatch")

    # Preserved serializer fixture pairs: all selected lags, roundtrip in actual codec and independent size verification.
    groups = {}
    if args.fixtures:
        for path in sorted(args.fixtures.resolve().glob("*.bin")):
            name, step = path.stem.rsplit("-", 1)
            groups.setdefault(name, {})[int(step)] = path
        if not groups:
            raise RuntimeError("selected fixture directory is empty")
    if args.carrier_fixtures:
        groups["existing_cumulative_birth_carriers"] = {i: args.carrier_fixtures.resolve() / f"carrier{i:02}.bin" for i in range(16)}
    pairs, fixture_pins = [], {}
    for name, steps in groups.items():
        if sorted(steps) != list(range(16)):
            raise RuntimeError("expected closed authored16-image group: " + name)
        for path in steps.values():
            if not path.is_file() or path.stat().st_size > 65536:
                raise RuntimeError("fixture missing/oversize: " + str(path))
            fixture_pins[str(path)] = {"sha256": sha(path), "size": path.stat().st_size}
        for lag in (1, 2, 4, 6, 8, 15):
            for step in range(lag, 16):
                a, b = steps[step - lag], steps[step]
                pairs.append((a, b))
                expected = len(reference(a.read_bytes(), b.read_bytes()))
                result["fixture_pairs"].append({"group": name, "lag": lag, "step": step, "required": expected,
                                                 "base": str(a), "target": str(b)})
    result["fixture_inputs"] = fixture_pins
    if pairs:
        manifest = out / "pairs.txt"
        manifest.write_text("".join(str(a) + "\n" + str(b) + "\n" for a, b in pairs))
        proc = run("fixtures", [str(binary), "fixtures", str(manifest)])
        rows = [json.loads(line) for line in proc.stdout.splitlines()]
        if len(rows) != len(pairs) + 1 or rows[-1]["pairs"] != len(pairs):
            raise RuntimeError("fixture coverage is incomplete")
        for row, wanted in zip(rows[:-1], result["fixture_pairs"]):
            if row["encoded"] != wanted["required"]:
                raise RuntimeError("actual codec size differs from independent encoder")
            wanted.update(actual=row["encoded"], base_size=row["base"], target_size=row["target"], passed=True)
        result["fixtures"] = rows[-1]
        if any(sha(Path(path)) != pin["sha256"] for path, pin in fixture_pins.items()):
            raise RuntimeError("read-only fixture input changed")

    if not args.no_mutants:
        source = (stage / "state_delta.cpp").read_text()
        mutants = (
            ("ignore-context", "crypto_verify32(wire + 8, basis->identity.context)", "false", "core"),
            ("ignore-base-digest", "if (crypto_verify32(wire + 60, digest))", "if (false)", "core"),
            ("ignore-target-digest", "if (crypto_verify32(wire + 92, digest))", "if (false)", "core"),
            ("accept-stale", "if (target_identity.sequence <= last_applied_sequence)", "if (false)", "core"),
            ("accept-unchanged-literal", "if (wire[at + i] == Reference(*basis, begin + i))", "if (false)", "core"),
            ("ignore-output-capacity", "if (capacity < target_size)", "if (capacity == UINT32_MAX)", "core"),
            ("accept-scalar-overlap", "Overlap(identity, sizeof(*identity), size, sizeof(*size))", "false", "aliases"),
            ("accept-descriptor-overlap", "!Overlap(p, n, &image, sizeof(image)) && ", "", "aliases"),
        )
        for label, old, new, mode in mutants:
            if source.count(old) != 1:
                raise RuntimeError("mutation seam changed: " + label)
            path = out / (label + ".cpp")
            path.write_text(source.replace(old, new))
            mutant = build(label, path)
            proc = subprocess.run([str(mutant), mode], env=env, capture_output=True, text=True, timeout=20)
            (out / (label + ".stdout")).write_text(proc.stdout)
            (out / (label + ".stderr")).write_text(proc.stderr)
            killed = proc.returncode == 2 and "FAIL:" in proc.stderr
            result["mutations"].append({"name": label, "exit": proc.returncode, "killed": killed, "reason": proc.stderr.strip()})
            if not killed:
                save(); raise RuntimeError("mutant not meaningfully rejected: " + label)

    if args.syntax_targets:
        for target in ("linux", "windows"):
            compiler = cxx if target == "linux" else deps.DATA / "llvm-mingw/bin/i686-w64-mingw32-clang++"
            target_flags = ["--target=i686-pc-linux-gnu", "--sysroot=" + str(deps.SYSROOT)] if target == "linux" else []
            run(target + "-syntax", [str(compiler), *target_flags, "-std=c++17", "-Wall", "-Wextra", "-Werror", "-fsyntax-only",
                                     "-I" + str(stage), str(stage / "state_delta.cpp")])
    result["passed"] = all(row["passed"] for row in result["stages"]) and all(row["killed"] for row in result["mutations"])
    if not inputs_unchanged():
        result["passed"] = False
    save()
    print(json.dumps({"receipt": str(receipt), "passed": result["passed"], "core": result["core"], "loss": result["loss"],
                      "aliases": result["aliases"], "fixture_pairs": len(pairs), "goldens": len(result["goldens"]),
                      "mutants": len(result["mutations"])}, indent=2))
    return 0 if result["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
